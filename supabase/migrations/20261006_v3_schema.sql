-- 1. ENUMS & EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

DO $$ BEGIN
    CREATE TYPE user_role AS ENUM ('customer', 'admin');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE order_status AS ENUM ('Menunggu Pembayaran', 'Dibayar', 'Dikemas', 'Dikirim', 'Selesai', 'Dibatalkan');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE coupon_type AS ENUM ('fixed', 'percentage');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

-- 2. PROFILES (Sinkron dengan auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(30),
    avatar_url TEXT,
    role user_role DEFAULT 'customer',
    address_line TEXT,
    city VARCHAR(100),
    postal_code VARCHAR(10),
    preferred_size VARCHAR(10) DEFAULT 'M',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. KATEGORI PRODUK
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(100) UNIQUE NOT NULL,
    gender VARCHAR(20) DEFAULT 'unisex',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. PRODUK BUSANA (Spesifikasi Uniqlo LifeWear Lengkap)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) UNIQUE NOT NULL,
    gender VARCHAR(20) DEFAULT 'unisex',
    price NUMERIC(12, 2) NOT NULL,
    original_price NUMERIC(12, 2),
    stock INT NOT NULL DEFAULT 0,
    description TEXT,
    fabric_details TEXT,
    care_instructions TEXT,
    colors JSONB DEFAULT '[]'::jsonb,
    sizes TEXT[] DEFAULT ARRAY['S', 'M', 'L', 'XL'],
    size_measurements JSONB DEFAULT '[]'::jsonb,
    image_url TEXT NOT NULL,
    gallery_images TEXT[] DEFAULT ARRAY[]::TEXT[],
    rating NUMERIC(2, 1) DEFAULT 4.8,
    reviews_count INT DEFAULT 0,
    is_featured BOOLEAN DEFAULT FALSE,
    is_new BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. KUPON PROMO
CREATE TABLE IF NOT EXISTS public.coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    type coupon_type DEFAULT 'fixed',
    discount_amount NUMERIC(12, 2) NOT NULL,
    min_purchase NUMERIC(12, 2) DEFAULT 0,
    max_discount NUMERIC(12, 2),
    usage_limit INT DEFAULT 100,
    used_count INT DEFAULT 0,
    valid_until TIMESTAMP WITH TIME ZONE,
    is_active BOOLEAN DEFAULT TRUE,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. PESANAN
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    order_number VARCHAR(50) UNIQUE NOT NULL,
    customer_name VARCHAR(150) NOT NULL,
    customer_phone VARCHAR(50) NOT NULL,
    customer_address TEXT NOT NULL,
    shipping_courier VARCHAR(100) DEFAULT 'J&T Express',
    shipping_cost NUMERIC(12, 2) DEFAULT 15000,
    tracking_number VARCHAR(100),
    coupon_id BIGINT REFERENCES public.coupons(id) ON DELETE SET NULL,
    discount_amount NUMERIC(12, 2) DEFAULT 0,
    payment_method VARCHAR(50) DEFAULT 'QRIS',
    total_amount NUMERIC(12, 2) NOT NULL,
    status order_status DEFAULT 'Dibayar',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. RINCIAN PESANAN
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    product_name VARCHAR(255) NOT NULL,
    selected_size VARCHAR(10),
    selected_color VARCHAR(50),
    price NUMERIC(12, 2) NOT NULL,
    quantity INT NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL
);

-- 8. ULASAN PEMBELI
CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
    user_id UUID,
    reviewer_name VARCHAR(100) NOT NULL,
    rating INT CHECK (rating >= 1 AND rating <= 5),
    size_purchased VARCHAR(10),
    fit_rating VARCHAR(30) DEFAULT 'Pas Sesuai Ukuran',
    comment TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 9. DAFTAR KEINGINAN (WISHLIST)
CREATE TABLE IF NOT EXISTS public.wishlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    UNIQUE(user_id, product_id)
);

