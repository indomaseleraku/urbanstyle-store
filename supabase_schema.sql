-- ==============================================================================
-- 11. ATOMIC TRANSACTION STORED PROCEDURE: PEMOTONGAN STOK KEBUSANAN ANTI-RACE CONDITION
-- ==============================================================================
CREATE OR REPLACE FUNCTION atomic_deduct_stock(p_product_id BIGINT, p_quantity INT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_current_stock INT;
BEGIN
    SELECT stock INTO v_current_stock FROM products WHERE id = p_product_id FOR UPDATE;
    
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Produk ID % tidak ditemukan.', p_product_id;
    END IF;

    IF v_current_stock < p_quantity THEN
        RAISE EXCEPTION 'Stok tidak mencukupi (Tersisa: %, Diminta: %).', v_current_stock, p_quantity;
    END IF;

    UPDATE products SET stock = stock - p_quantity WHERE id = p_product_id;
    RETURN TRUE;
END;
$$;

